"""Build the data behind ChromaRecover's project page, film and in-browser lab by running ChromaRecover itself.

Writes assets/chromarecover/:
  chromarecover-<version>-py3-none-any.whl  the exact engine the lab runs in the browser (reproducible build of the checkout)
  data.json      versions, wheel hash, gallery results, the decision of each case, benchmarks, tests, documented external runs
  film.json      one recovery traced stage by stage (tiles, colours, every scored hypothesis, the decision), plus its decoy
  gallery/<id>/  input.png and the top candidates' overlay / evidence / mask, as the lab shows them

Every image is generated by ChromaRecover's own generators (chromarecover.synthetic); no third-party picture is used.
The same RecoverConfig as the lab is used, so the browser can be checked against these native results
(tools/chromarecover_parity.py). The checkout must be clean so the recorded commit really is the code that ran.

    python tools/chromarecover_showcase.py --python C:/path/to/venv/python.exe [--repo ../ChromaRecover] [--skip-slow]
"""
